# ==================== 数据生成 ====================

def generate_all_chapters():
    """生成第1101-1500章的全部数据"""
    records = []
    stats = {"total": 0, "plant": 0, "reap": 0, "maintain": 0}

    for chapter_num in range(1101, 1501):
        if chapter_num not in CHAPTERS:
            print(f"警告：第{chapter_num}章缺少定义，跳过")
            continue

        title, summary = CHAPTERS[chapter_num]

        # 确定resolution_type
        if chapter_num in FORESHADOW_PLANT:
            res_type_1 = "埋设"
            res_type_2 = "维持"
            stats["plant"] += 1
        elif chapter_num in FORESHADOW_REAP:
            res_type_1 = "回收"
            res_type_2 = "维持"
            stats["reap"] += 1
        else:
            res_type_1 = "维持"
            res_type_2 = "维持"
            stats["maintain"] += 1

        # POV分配
        pov1 = get_pov_for_scene(chapter_num, 0)
        pov2 = get_pov_for_scene(chapter_num, 1, pov1)
        # 确保两个场景POV不同
        while pov2 == pov1:
            pov2 = OTHER_POVS[(chapter_num + 1) % len(OTHER_POVS)]
            if pov2 == pov1:
                pov2 = MAIN_POV if pov1 != MAIN_POV else OTHER_POVS[0]

        # 参与者
        participants1 = get_participants(chapter_num, pov1)
        participants2 = get_participants(chapter_num, pov2)

        # 情感弧线
        emotion1 = get_emotion_arc(chapter_num, 0)
        emotion2 = get_emotion_arc(chapter_num, 1)

        # 场景描述
        desc1, desc2 = generate_scene_descriptions(chapter_num, title, summary)

        chapter_data = {
            "chapter": chapter_num,
            "chapter_constraint_summary": {
                "title": title,
                "summary": summary
            },
            "scenes": [
                {
                    "scene_id": f"s{chapter_num}_1",
                    "description": desc1,
                    "word_count_budget": 1200,
                    "pov_char_id": pov1,
                    "participants": participants1,
                    "emotional_arc": emotion1,
                    "resolution_type": res_type_1
                },
                {
                    "scene_id": f"s{chapter_num}_2",
                    "description": desc2,
                    "word_count_budget": 1200,
                    "pov_char_id": pov2,
                    "participants": participants2,
                    "emotional_arc": emotion2,
                    "resolution_type": res_type_2
                }
            ]
        }

        records.append((
            "NOV-001",
            chapter_num,
            json.dumps(chapter_data["chapter_constraint_summary"], ensure_ascii=False),
            json.dumps(chapter_data["scenes"], ensure_ascii=False)
        ))
        stats["total"] += 1

    return records, stats


