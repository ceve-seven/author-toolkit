def get_emotion_arc(chapter, scene_idx):
    """为场景生成情感弧线，确保start和end不同"""
    idx = (chapter * 2 + scene_idx) % len(EMOTION_PAIRS)
    return {
        "start_emotion": EMOTION_PAIRS[idx][0],
        "end_emotion": EMOTION_PAIRS[idx][1]
    }


